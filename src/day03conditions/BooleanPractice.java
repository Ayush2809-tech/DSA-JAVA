package day03conditions;

import java.util.Scanner;

public class BooleanPractice {
    public static void main(String[] args) {
        Scanner sc = new Scanner (System.in);
        int n = sc.nextInt();
        boolean isPositive =n>0;
        if(isPositive){
            System.out.println(isPositive);
        }
        else{
            System.out.println(isPositive);
        }
    }
}
